#!/usr/bin/env python3
"""Write a C source made of functions cut from the pinned ESP-IDF, for a host test to compile.

Usage: extract_sdk_functions.py <spec.json> <output.c> [--idf <IDF_PATH>]

The spec names the header the output includes first and the functions to cut:

    {"include": "test_sdk.h",
     "functions": [{"file": "components/esp-tls/esp_tls.c", "name": "esp_tls_conn_write",
                    "replace": [["esp_tls_conn_write", "__real_esp_tls_conn_write"]]}]}

Each function is found by its definition, which must be unique in its file,
and copied whole. Each replacement swaps every occurrence of a text that is
not part of a longer identifier, and must occur at least once. A #line
directive before each function names its SDK file and line, so diagnostics,
sanitizer reports and coverage point at the SDK source. A function that
cannot be found exactly once, an unclosed one and an unused replacement are
errors, so SDK changes fail the build instead of compiling something else.
The output is rewritten only when its text changes.
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys

# Comments, string and character literals, and braces, in source order.
TOKENS = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|[{}]', re.S)


def quoted(path):
    return '"' + str(path).replace('\\', '\\\\').replace('"', '\\"') + '"'


def definition(text, name, where):
    """Return (start, end) of the definition of the C function name in text."""
    # A definition starts in the first column, unlike a call or a declaration in a body.
    pattern = re.compile(r'^(?=\S)[^\n;{}#]*\b' + re.escape(name) + r'\s*\([^;{}]*\)\s*\{', re.M)
    matches = list(pattern.finditer(text))
    if len(matches) != 1:
        raise ValueError(f'{where}: {len(matches)} definitions of {name}()')
    start = matches[0].start()
    depth = 0
    for token in TOKENS.finditer(text, matches[0].end() - 1):
        if token.group() == '{':
            depth += 1
        elif token.group() == '}':
            depth -= 1
            if depth == 0:
                return start, token.end()
    raise ValueError(f'{where}: {name}() is not closed')


def extract(spec, idf, output):
    lines = ['// Generated by tests/extract_sdk_functions.py from the pinned ESP-IDF; do not edit.',
             f'#include {quoted(spec["include"])}']
    for function in spec['functions']:
        path = Path(idf) / function['file']
        where = f'$IDF_PATH/{function["file"]}'
        text = path.read_text()
        start, end = definition(text, function['name'], where)
        body = text[start:end]
        for old, new in function.get('replace', []):
            pattern = re.compile(r'(?<!\w)' + re.escape(old) + r'(?!\w)')
            body, count = pattern.subn(lambda _: new, body)
            if not count:
                raise ValueError(f'{where}: {function["name"]}() has no {old!r} to replace')
        lines.append(f'#line {text.count(chr(10), 0, start) + 1} {quoted(path)}')
        lines.extend(body.split('\n'))
        lines.append(f'#line {len(lines) + 2} {quoted(output)}')
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('spec', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--idf', default=os.environ.get('IDF_PATH', Path.home() / '.espressif/v6.1/esp-idf'))
    args = parser.parse_args(argv)
    try:
        text = extract(json.loads(args.spec.read_text()), args.idf, args.output.resolve())
    except (OSError, ValueError, KeyError) as error:
        print(f'{args.spec}: {error}', file=sys.stderr)
        return 1
    if not args.output.exists() or args.output.read_text() != text:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
